#!/usr/bin/env bash
# Regenerate paper-v2/tables/constants.tex from the source tree and built
# binaries. Run after `make build` at the tagged release.
set -euo pipefail
ROOT="$(cd "$(dirname "$0")/../.." && pwd)"
OUT="${1:-$ROOT/paper-v2/tables/constants.tex}"
TAG="${RELEASE_TAG:-$(git -C "$ROOT" describe --tags --exact-match 2>/dev/null || echo untagged)}"
go_loc=$(find "$ROOT/cmd" "$ROOT/internal" -name '*.go' | xargs cat | wc -l | tr -d ' ')
rs_loc=$(find "$ROOT/agent/src" -name '*.rs' | xargs cat | wc -l | tr -d ' ')
srv=$(stat -f %z "$ROOT/bin/boxed")
agt=$(stat -f %z "$ROOT/bin/boxed-agent")
cap=$(grep -E 'const MAX_INLINE_SIZE' "$ROOT/agent/src/fs_watcher.rs" | sed -E 's/.*= *([0-9* ]+);.*/\1/' | python3 -c 'import sys;print(eval(sys.stdin.read()))')
mem=$(grep -A1 'MemoryMB <= 0' "$ROOT/internal/driver/driver.go" | tail -1 | grep -oE '[0-9]+' | head -1)
fmt_n() { python3 -c "print(f'{int($1):,}'.replace(',','{,}'))"; }
cat > "$OUT" <<EOF
% AUTO-GENERATED by bench/analyze/constants.sh -- do not edit by hand.
% Read off the source tree and built binaries at release $TAG.
%   BoxedGoLOC          find cmd internal -name '*.go' | xargs cat | wc -l
%   BoxedRustLOC        find agent/src -name '*.rs' | xargs cat | wc -l
%   BoxedServerBinSize  bin/boxed ($srv B)
%   BoxedAgentBinSize   bin/boxed-agent ($agt B, stripped)
%   BoxedInlineCap      agent/src/fs_watcher.rs: MAX_INLINE_SIZE
%   BoxedMemDefault     internal/driver/driver.go: SandboxConfig.Validate()
\\newcommand{\\BoxedReleaseTag}{$TAG\\xspace}
\\newcommand{\\BoxedGoLOC}{$(fmt_n $go_loc)\\xspace}
\\newcommand{\\BoxedRustLOC}{$(fmt_n $rs_loc)\\xspace}
\\newcommand{\\BoxedServerBinSize}{$(python3 -c "print(f'{$srv/1048576:.1f}')")\\,MiB\\xspace}
\\newcommand{\\BoxedAgentBinSize}{$(python3 -c "print(f'{$agt/1048576:.2f}')")\\,MiB\\xspace}
\\newcommand{\\BoxedInlineCap}{$(python3 -c "print($cap//1048576)")\\,MiB\\xspace}
\\newcommand{\\BoxedMemDefault}{$mem\\,MiB\\xspace}
EOF
echo "wrote $OUT (tag $TAG)"
